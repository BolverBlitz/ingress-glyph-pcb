Import("env")

import json
import re
from pathlib import Path


PROJECT_DIR = Path(env.subst("$PROJECT_DIR"))
WEB_DIR = PROJECT_DIR / "WebUI"
OUTPUT = PROJECT_DIR / "src" / "web_ui.h"

ASSETS = (
    ("MAIN_PAGE", "index.html", "html"),
    ("DRAW_PAGE", "draw.html", "html"),
    ("SETTINGS_PAGE", "settings.html", "html"),
    ("NEARBY_PAGE", "nearby.html", "html"),
    ("MAIN_CSS", "index.css", "css"),
    ("DRAW_CSS", "draw.css", "css"),
    ("SETTINGS_CSS", "settings.css", "css"),
    ("NEARBY_CSS", "nearby.css", "css"),
    ("FLASHLIGHT_CSS", "flashlight.css", "css"),
    ("FLASHLIGHT_JS", "flashlight.js", "js"),
    ("PWA_MANIFEST", "manifest.webmanifest", "json"),
    ("SERVICE_WORKER", "sw.js", "js"),
    ("APP_ICON", "icon.svg", "svg"),
)


def minify_css(value):
    value = re.sub(r"/\*.*?\*/", "", value, flags=re.S)
    value = re.sub(r"\s+", " ", value)
    value = re.sub(r"\s*([{}:;,>+~])\s*", r"\1", value)
    return value.strip().replace(";}", "}")


def minify_js(value):
    # Conservative: remove indentation/newlines without rewriting strings.
    return "".join(line.strip() for line in value.splitlines())


def minify_html(value):
    value = re.sub(r"<!--(?!\[if).*?-->", "", value, flags=re.S)
    value = re.sub(
        r"<script>(.*?)</script>",
        lambda match: "<script>" + minify_js(match.group(1)) + "</script>",
        value,
        flags=re.S | re.I,
    )
    value = re.sub(r">\s+<", "><", value)
    return value.strip()


def minify(name, kind):
    value = (WEB_DIR / name).read_text(encoding="utf-8")
    if kind == "css":
        return minify_css(value)
    if kind == "html" or kind == "svg":
        return minify_html(value)
    if kind == "js":
        return minify_js(value)
    if kind == "json":
        return json.dumps(json.loads(value), separators=(",", ":"), ensure_ascii=False)
    raise ValueError(f"Unknown WebUI asset type: {kind}")


def generate_header():
    lines = [
        "// AUTO-GENERATED by scripts/generate_web_ui.py from WebUI/.",
        "// Do not edit this file directly.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
    ]
    for constant, filename, kind in ASSETS:
        content = minify(filename, kind)
        if ')WEBUI"' in content:
            raise ValueError(f"Raw-string delimiter appears in {filename}")
        lines.append(
            f'const char {constant}[] PROGMEM = R"WEBUI({content})WEBUI";'
        )
    generated = "\n".join(lines) + "\n"
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Generated minified WebUI header: {OUTPUT.relative_to(PROJECT_DIR)}")


generate_header()
