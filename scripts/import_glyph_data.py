"""Import and compact glyph-predict-pwa glyph and normal-sequence data."""

import json
import re
import urllib.request
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data" / "glyph-predict-pwa"
GLYPHS_URL = "https://raw.githubusercontent.com/szres/glyph-predict-pwa/main/static/glyphs.json"
SEQUENCES_URL = "https://raw.githubusercontent.com/szres/glyph-predict-pwa/main/static/normal.json"

# Upstream letter -> this project's logical HTML/PCB node ID.
POINT_MAP = {
    "m": "0", "d": "1", "k": "2", "c": "3", "l": "4", "b": "5",
    "r": "6", "j": "7", "h": "8", "t": "9", "a": "a",
}


def download_json(url):
    request = urllib.request.Request(url, headers={"User-Agent": "ingress-glyph-pcb-importer"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def key(name):
    return re.sub(r"[^a-z0-9]", "", name.lower())


def cpp_string(value):
    return json.dumps(value, ensure_ascii=True)


def encoded_segments(points):
    try:
        logical = "".join(POINT_MAP[point] for point in points)
    except KeyError as error:
        raise ValueError(f"Unknown upstream glyph point: {error.args[0]}") from error
    return "".join(logical[index:index + 2] for index in range(len(logical) - 1))


def wrapped(values, width=12):
    return [values[index:index + width] for index in range(0, len(values), width)]


def main():
    glyphs = download_json(GLYPHS_URL)
    sequences = download_json(SEQUENCES_URL)
    if len(glyphs) > 255:
        raise ValueError("Glyph IDs no longer fit in uint8_t")

    aliases = {}
    for glyph_id, glyph in enumerate(glyphs):
        for name in glyph["name"]:
            alias = key(name)
            if alias in aliases and aliases[alias] != glyph_id:
                raise ValueError(f"Duplicate glyph alias: {name}")
            aliases[alias] = glyph_id

    compact_sequences = []
    for sequence in sequences:
        ids = []
        for name in sequence:
            alias = key(name)
            if alias not in aliases:
                raise ValueError(f"Sequence references unknown glyph: {name}")
            ids.append(aliases[alias])
        if not 2 <= len(ids) <= 5:
            raise ValueError(f"Unexpected sequence length: {len(ids)}")
        compact_sequences.append(ids)

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    (DATA_DIR / "glyphs.json").write_text(
        json.dumps(glyphs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    (DATA_DIR / "normal.json").write_text(
        json.dumps(sequences, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    glyph_lines = [
        '#include "glyphs.h"', "",
        "// Generated by scripts/import_glyph_data.py from glyph-predict-pwa.",
        "const GlyphDefinition GLYPHS[] = {",
    ]
    for glyph in glyphs:
        name = " / ".join(glyph["name"])
        glyph_lines.append(
            f"    {{{cpp_string(name)}, {cpp_string(encoded_segments(glyph['points']))}}},"
        )
    glyph_lines.extend([
        "};", "",
        "const size_t GLYPH_COUNT = sizeof(GLYPHS) / sizeof(GLYPHS[0]);", "",
    ])
    (ROOT / "src" / "glyphs.cpp").write_text("\n".join(glyph_lines), encoding="utf-8")

    flat = []
    descriptors = []
    for ids in compact_sequences:
        descriptors.append((len(flat), len(ids)))
        flat.extend(ids)
    sequence_lines = [
        '#include "glyph_sequences.h"', "",
        "// Generated by scripts/import_glyph_data.py. Sequences store uint8_t glyph IDs.",
        "const uint8_t GLYPH_SEQUENCE_IDS[] = {",
    ]
    for row in wrapped(flat):
        sequence_lines.append("    " + ", ".join(map(str, row)) + ",")
    sequence_lines.extend(["};", "", "const GlyphSequenceDefinition GLYPH_SEQUENCES[] = {"])
    for row in wrapped(descriptors, 8):
        sequence_lines.append(
            "    " + ", ".join(f"{{{offset}, {length}}}" for offset, length in row) + ","
        )
    sequence_lines.extend([
        "};", "",
        "const size_t GLYPH_SEQUENCE_COUNT =",
        "    sizeof(GLYPH_SEQUENCES) / sizeof(GLYPH_SEQUENCES[0]);", "",
    ])
    (ROOT / "src" / "glyph_sequences.cpp").write_text(
        "\n".join(sequence_lines), encoding="utf-8"
    )
    print(f"Imported {len(glyphs)} glyphs and {len(sequences)} sequences")


if __name__ == "__main__":
    main()
